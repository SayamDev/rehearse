export function translate(lang: string | undefined, key: UiKey): string {
  return (lang && T[lang]?.[key]) || EN[key];
}

/** Returns t(key) in the practice language. Before the page has loaded settings, English. */
export function useT(): (key: UiKey) => string {
  const { profile } = useStore();
  const lang = profile.settings.language;
  return (key) => translate(lang, key);
}

export const UI_LANGUAGES = Object.keys(T);

/** Keys a language hasn't translated yet (they fall back to English). */
export function missingKeys(lang: string): UiKey[] {
  return (Object.keys(EN) as UiKey[]).filter((k) => !T[lang]?.[k]);
}
export const UI_KEYS = Object.keys(EN) as UiKey[];
